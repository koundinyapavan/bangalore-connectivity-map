const {chromium}=require('playwright'),assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8765/research.html');
 await page.waitForFunction(()=>document.querySelector('#summary').textContent.includes('974 catalogue'));
 assert.equal(await page.locator('#builder option').count(),64);
 await page.selectOption('#line','Purple');await page.selectOption('#distance','0.5');await page.fill('#query','Brigade Woods');
 assert.equal(await page.locator('#rows tr').count(),1);assert.match(await page.locator('#rows').innerText(),/Operating/);
 await page.screenshot({path:'audit/research-desktop.png',fullPage:true});
 await page.fill('#query','');await page.selectOption('#line','');await page.selectOption('#builder','Tata Housing');
 assert.match(await page.locator('#rows').innerText(),/New Haven/);
 await page.selectOption('#builder','');await page.selectOption('#admission','unmapped');await page.fill('#query','Oakville');
 assert.equal(await page.locator('#rows a[href^="index.html"]').count(),0);
 await page.goto('http://127.0.0.1:8765/index.html?project=Brigade%20Woods');
 await page.waitForFunction(()=>document.getElementById('count').textContent.includes('1 of'));
 assert.match(await page.locator('#listBody').innerText(),/Brigade Woods/);
 await page.locator('#lrow-0').click();await page.waitForSelector('.leaflet-popup-content');
 const popup=await page.locator('.leaflet-popup-content').innerText();
 for(const text of ['Operating','Under construction','Union-approved','Other proposal','not a 3 BHK quote'])assert(popup.includes(text),text);
 await page.screenshot({path:'audit/map-desktop.png',fullPage:true});
 await page.locator('.leaflet-popup-close-button').click();await page.locator('#reset').click();
 await page.waitForFunction(()=>{const t=document.getElementById('count').textContent;const m=t.match(/(\d+) of (\d+)/);return m&&m[1]===m[2]});
 for(const v of ['ready','uc','mixed'])await page.locator('.fStatus[value="'+v+'"]').uncheck();
 await page.setViewportSize({width:390,height:844});await page.goto('http://127.0.0.1:8765/research.html');
 await page.waitForFunction(()=>document.querySelector('#rows tr'));
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
 await page.fill('#query','Trifecta');await page.screenshot({path:'audit/research-mobile.png',fullPage:true});
 assert.deepEqual(errors,[]);console.log('PASS: desktop/mobile catalogue, builder/line/distance filters, withheld pins, map deep-link, four metro stages and reset; no browser exceptions.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
